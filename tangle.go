package main

import (
	"bytes"
	"fmt"
	"go/scanner"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/ast"
	"github.com/yuin/goldmark/text"
	"golang.org/x/tools/imports"
)

const (
	toolName = "go-lit"
	header   = "// Code generated by " + toolName + ". DO NOT EDIT.\n"
	maxDepth = 256 // same limit the C preprocessor typically uses
)

var (
	fileRe  = regexp.MustCompile(`^//\s*file:\s*(\S+)\s*$`)
	defRe   = regexp.MustCompile(`^//==\s*(\S+)\s*==//$`)
	refRe   = regexp.MustCompile(`^(\s*)//::\s*(\S+)\s*:://\s*$`)
	buildRe = regexp.MustCompile(`^\s*(//go:build\s|// \+build\s)`)
)

// line is one line of Go code plus where it came from in the Markdown.
// n == 0 means the line has no source position (e.g. hoisted or synthetic).
type line struct {
	text string
	src  string
	n    int
}

// Program is the symbol table built from one or more Markdown documents.
type Program struct {
	chunks map[string][]line // named macro chunks (//== name ==//)
	files  map[string][]line // output files (// file: path)
	order  []string          // output files in first-seen order
}

func NewProgram() *Program {
	return &Program{chunks: map[string][]line{}, files: map[string][]line{}}
}

// Parse walks the Markdown AST and collects every ```go fenced block that
// starts with a "// file:" or "//== name ==//" marker. Repeated definitions
// of the same file or chunk are appended in document order.
func (p *Program) Parse(srcName string, data []byte) error {
	doc := goldmark.New().Parser().Parse(text.NewReader(data))
	return ast.Walk(doc, func(n ast.Node, entering bool) (ast.WalkStatus, error) {
		fb, ok := n.(*ast.FencedCodeBlock)
		if !entering || !ok || string(fb.Language(data)) != "go" {
			return ast.WalkContinue, nil
		}
		segs := fb.Lines()
		var lines []line
		for i := 0; i < segs.Len(); i++ {
			s := segs.At(i)
			// Lines are contiguous, so the line number of the first one is enough.
			n := bytes.Count(data[:s.Start], []byte("\n")) + 1
			lines = append(lines, line{strings.TrimRight(string(s.Value(data)), "\r\n"), srcName, n})
		}
		// The marker is the first non-blank line.
		for len(lines) > 0 && strings.TrimSpace(lines[0].text) == "" {
			lines = lines[1:]
		}
		if len(lines) == 0 {
			return ast.WalkContinue, nil
		}
		first := strings.TrimSpace(lines[0].text)
		if m := fileRe.FindStringSubmatch(first); m != nil {
			path := filepath.Clean(m[1])
			if _, seen := p.files[path]; !seen {
				p.order = append(p.order, path)
			} else {
				p.files[path] = append(p.files[path], line{}) // blank line between blocks
			}
			p.files[path] = append(p.files[path], lines[1:]...)
		} else if m := defRe.FindStringSubmatch(first); m != nil {
			p.chunks[m[1]] = append(p.chunks[m[1]], lines[1:]...)
		}
		return ast.WalkContinue, nil
	})
}

// expand recursively substitutes //:: name :://  references, prefixing the
// substituted lines with the indentation of the reference.
func (p *Program) expand(in []line, indent string, stack []string) ([]line, error) {
	if len(stack) > maxDepth {
		return nil, fmt.Errorf("macro recursion deeper than %d: %s", maxDepth, strings.Join(stack, " -> "))
	}
	var out []line
	inRaw := multilineTokenInteriors(in) // re-indenting these would change string contents
	for i, l := range in {
		m := refRe.FindStringSubmatch(l.text)
		if m == nil || inRaw[i] {
			if strings.TrimSpace(l.text) != "" && !inRaw[i] {
				l.text = indent + l.text
			}
			out = append(out, l)
			continue
		}
		name := m[2]
		if slices.Contains(stack, name) {
			return nil, fmt.Errorf("%s:%d: circular reference: %s -> %s", l.src, l.n, strings.Join(stack, " -> "), name)
		}
		body, ok := p.chunks[name]
		if !ok {
			return nil, fmt.Errorf("%s:%d: undefined chunk %q", l.src, l.n, name)
		}
		sub, err := p.expand(body, indent+m[1], append(stack, name))
		if err != nil {
			return nil, err
		}
		out = append(out, sub...)
	}
	return out, nil
}

// Tangle produces the formatted contents of every output file, keyed by
// path relative to outDir. With lineMap, //line directives pointing back at
// the Markdown are emitted (paths relative to the output file's directory).
func (p *Program) Tangle(outDir string, lineMap bool) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, path := range p.order {
		lines, err := p.expand(p.files[path], "", []string{"file:" + path})
		if err != nil {
			return nil, err
		}
		target := filepath.Join(outDir, path)
		raw := assemble(lines, filepath.Dir(target), lineMap)
		src, err := imports.Process(target, raw, &imports.Options{Comments: true, TabIndent: true, TabWidth: 8})
		if err != nil {
			return nil, fmt.Errorf("%s: %w\n--- tangled source ---\n%s", path, err, numbered(raw))
		}
		out[path] = src
	}
	return out, nil
}

// assemble hoists build constraints to the top, prepends the generated-code
// header and optionally interleaves //line directives.
func assemble(lines []line, targetDir string, lineMap bool) []byte {
	var tags, body []line
	var goBuild []string
	for _, l := range lines {
		if !buildRe.MatchString(l.text) {
			body = append(body, l)
			continue
		}
		t := strings.TrimSpace(l.text)
		if expr, ok := strings.CutPrefix(t, "//go:build "); ok {
			if !slices.Contains(goBuild, expr) {
				goBuild = append(goBuild, expr)
			}
		} else if !slices.ContainsFunc(tags, func(x line) bool { return x.text == t }) {
			tags = append(tags, line{text: t})
		}
	}

	var b strings.Builder
	b.WriteString(header + "\n")
	if len(goBuild) == 1 {
		b.WriteString("//go:build " + goBuild[0] + "\n")
	} else if len(goBuild) > 1 {
		b.WriteString("//go:build (" + strings.Join(goBuild, ") && (") + ")\n")
	}
	for _, t := range tags {
		b.WriteString(t.text + "\n")
	}
	if len(goBuild)+len(tags) > 0 {
		b.WriteString("\n")
	}

	var unsafe map[int]bool
	if lineMap {
		unsafe = multilineTokenInteriors(body)
	}
	for i, l := range body {
		// A directive is needed wherever the mapping breaks, after blank
		// lines (gofmt may collapse them) and before top-level declarations
		// (gofmt may insert blank lines between them). Never inside raw
		// strings or block comments (e.g. cgo preambles), where it would
		// change meaning.
		if lineMap && l.n > 0 && strings.TrimSpace(l.text) != "" && !unsafe[i] {
			topLevel := !strings.ContainsAny(l.text[:1], " \t})")
			if i == 0 || topLevel || body[i-1].src != l.src || body[i-1].n != l.n-1 || strings.TrimSpace(body[i-1].text) == "" {
				rel, err := filepath.Rel(targetDir, l.src)
				if err != nil {
					rel = l.src
				}
				fmt.Fprintf(&b, "//line %s:%d\n", filepath.ToSlash(rel), l.n)
			}
		}
		b.WriteString(l.text + "\n")
	}
	return []byte(b.String())
}

// multilineTokenInteriors returns indexes of lines that start inside a raw
// string literal or a /* */ comment.
func multilineTokenInteriors(body []line) map[int]bool {
	var src strings.Builder
	for _, l := range body {
		src.WriteString(l.text + "\n")
	}
	fset := token.NewFileSet()
	f := fset.AddFile("", -1, src.Len())
	var s scanner.Scanner
	s.Init(f, []byte(src.String()), func(token.Position, string) {}, scanner.ScanComments)
	res := map[int]bool{}
	for {
		pos, tok, lit := s.Scan()
		if tok == token.EOF {
			return res
		}
		if tok != token.STRING && tok != token.COMMENT {
			continue
		}
		start := fset.Position(pos).Line
		end := start + strings.Count(lit, "\n")
		for ln := start + 1; ln <= end; ln++ {
			res[ln-1] = true // body index is line-1
		}
	}
}

func numbered(src []byte) string {
	var b strings.Builder
	for i, l := range strings.Split(strings.TrimRight(string(src), "\n"), "\n") {
		fmt.Fprintf(&b, "%4d  %s\n", i+1, l)
	}
	return b.String()
}

// WriteFiles writes the tangled outputs, skipping files whose content is
// unchanged so repeated go generate runs don't touch mtimes.
func WriteFiles(outDir string, files map[string][]byte, protect string) error {
	for path, src := range files {
		target := filepath.Join(outDir, path)
		if protect != "" && sameFile(target, protect) {
			return fmt.Errorf("refusing to overwrite %s (it holds the go:generate directive)", target)
		}
		if old, err := os.ReadFile(target); err == nil && bytes.Equal(old, src) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func sameFile(a, b string) bool {
	aa, err1 := filepath.Abs(a)
	bb, err2 := filepath.Abs(b)
	return err1 == nil && err2 == nil && aa == bb
}
